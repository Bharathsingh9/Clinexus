"""Clinical Case Schemas.

Specification (SPEC 4.1, 4.2, 6, Appendix A5).
Models: ClinicalCase, StructuredSymptom, PatientContext, ClarificationRequest, CandidateHypothesis.
Rules:
- Pydantic v2
- schema_version="1.0"
- extra="forbid"
- Enum statuses
- Explicit UNKNOWN or null with reason
- Timezone-aware UTC timestamps
"""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional, Tuple
import uuid
from pydantic import BaseModel, ConfigDict, Field, field_validator


class PolarityEnum(str, Enum):
    PRESENT = "PRESENT"
    ABSENT = "ABSENT"


class OriginEnum(str, Enum):
    STATED = "STATED"
    INFERRED = "INFERRED"


class ClarificationStatusEnum(str, Enum):
    PENDING = "PENDING"
    ANSWERED = "ANSWERED"
    DISMISSED = "DISMISSED"


class CaseSubmission(BaseModel):
    """Raw clinical case submission from clinician or user."""
    submission_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    raw_text: str = Field(..., min_length=1, description="Raw narrative text submitted for analysis")
    submitted_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    schema_version: str = Field(default="1.0")

    model_config = ConfigDict(extra="forbid")


class SourceSpan(BaseModel):
    """Source text span representation."""
    start: int = Field(..., ge=0, description="Start offset into original clinical text")
    end: int = Field(..., ge=0, description="End offset into original clinical text")

    model_config = ConfigDict(extra="forbid")

    @field_validator("end")
    @classmethod
    def validate_end_after_start(cls, v: int, info) -> int:
        start = info.data.get("start")
        if start is not None and v < start:
            raise ValueError("Span end offset must be >= start offset")
        return v


class StructuredSymptom(BaseModel):
    """Extracted finding/symptom from clinical narrative."""
    finding_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    term: str = Field(..., min_length=1, description="Raw surface form mentioned in text")
    normalized_term: Optional[str] = Field(None, description="Mapped term in local vocab, or null if unmapped")
    vocabulary: str = Field(default="LOCAL", description="Controlled vocabulary reference")
    polarity: PolarityEnum = Field(..., description="PRESENT or ABSENT; negations kept as ABSENT, never UNKNOWN")
    onset: Optional[str] = Field(None, description="Reported onset or null if unknown")
    duration: Optional[str] = Field(None, description="Reported duration or null if unknown")
    severity: Optional[str] = Field(None, description="Reported severity or null if unknown")
    progression: Optional[str] = Field(None, description="Progression course or null if unknown")
    associated_symptoms: List[str] = Field(default_factory=list)
    source_span: SourceSpan = Field(..., description="Character offsets into original narrative")
    origin: OriginEnum = Field(..., description="STATED in text or INFERRED by reasoning")
    uncertainty_note: Optional[str] = Field(None, description="Required for INFERRED origin items")
    schema_version: str = Field(default="1.0")

    model_config = ConfigDict(extra="forbid")

    @field_validator("uncertainty_note")
    @classmethod
    def validate_inferred_note(cls, v: Optional[str], info) -> Optional[str]:
        origin = info.data.get("origin")
        if origin == OriginEnum.INFERRED and not v:
            raise ValueError("Inferred findings must carry an uncertainty_note.")
        return v


class PatientContext(BaseModel):
    """Demographics, history, medications, allergies, and vitals."""
    context_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    history: List[str] = Field(default_factory=list)
    medications: List[str] = Field(default_factory=list)
    allergies: List[str] = Field(default_factory=list)
    vitals: dict[str, str] = Field(default_factory=dict)
    schema_version: str = Field(default="1.0")

    model_config = ConfigDict(extra="forbid")


class ClarificationRequest(BaseModel):
    """Clarification question generated by the Clinical Text Clarifier."""
    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question_text: str = Field(..., min_length=1)
    is_blocking: bool = Field(..., description="True only when required field missing or contradiction unresolved")
    reason: str = Field(..., min_length=1, description="Explicit reason for clarification necessity")
    status: ClarificationStatusEnum = Field(default=ClarificationStatusEnum.PENDING)
    answer: Optional[str] = Field(None, description="Answer supplied by clinician")
    schema_version: str = Field(default="1.0")

    model_config = ConfigDict(extra="forbid")


class CandidateHypothesis(BaseModel):
    """Candidate consideration output by Symptom RAG Analyzer (SPEC App A5).
    
    Hypotheses are candidate considerations, never autonomous diagnoses (SAF-1).
    Must be supported by >= 1 retrieved passage.
    """
    hypothesis_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    label: str = Field(..., min_length=1, description="Candidate differential consideration")
    supporting_evidence_ids: List[str] = Field(..., min_length=1, description="Citations to retrieved evidence IDs")
    retrieval_scores: List[float] = Field(..., min_length=1, description="Similarity scores for supporting passages")
    schema_version: str = Field(default="1.0")

    model_config = ConfigDict(extra="forbid")

    @field_validator("retrieval_scores")
    @classmethod
    def validate_scores_match_ids(cls, v: List[float], info) -> List[float]:
        ids = info.data.get("supporting_evidence_ids")
        if ids is not None and len(v) != len(ids):
            raise ValueError("retrieval_scores count must match supporting_evidence_ids count")
        return v


class ClinicalCase(BaseModel):
    """Structured clinical case produced from raw submission narrative."""
    case_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    raw_text_hash: str = Field(..., min_length=64, max_length=64, description="SHA-256 hash of raw input text")
    age: Optional[int] = Field(None, ge=0, le=130, description="Patient age in years, or null if unknown")
    age_missing_reason: Optional[str] = Field(None, description="Reason if age is missing/null")
    sex: Optional[str] = Field(None, description="Patient sex, or UNKNOWN")
    chief_complaint: str = Field(..., min_length=1, description="Primary clinical presentation")
    symptom_duration: Optional[str] = Field(None, description="Duration of symptoms or null with reason")
    duration_missing_reason: Optional[str] = Field(None, description="Reason if symptom duration is null")
    structured_symptoms: List[StructuredSymptom] = Field(default_factory=list)
    patient_context: PatientContext = Field(default_factory=PatientContext)
    clarification_questions: List[ClarificationRequest] = Field(
        default_factory=list,
        max_length=5,
        description="At most 5 clarification questions"
    )
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    schema_version: str = Field(default="1.0")

    model_config = ConfigDict(extra="forbid")

    @field_validator("age_missing_reason")
    @classmethod
    def validate_age_reason(cls, v: Optional[str], info) -> Optional[str]:
        age = info.data.get("age")
        if age is None and not v:
            raise ValueError("When age is null, age_missing_reason must be provided.")
        return v

    @field_validator("duration_missing_reason")
    @classmethod
    def validate_duration_reason(cls, v: Optional[str], info) -> Optional[str]:
        duration = info.data.get("symptom_duration")
        if duration is None and not v:
            raise ValueError("When symptom_duration is null, duration_missing_reason must be provided.")
        return v
